// One launchd agent (macOS) or systemd user timer (Linux) per enabled job. A job is enabled on this
// machine exactly when its unit file exists; there is no other list. The units run `jobs exec <name>`.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { launchdCalendar, systemdCalendar } from './cron.mjs';

const run = (command, args) => spawnSync(command, args, { encoding: 'utf8' });
const check = (result, what) => {
  if (result.status !== 0) throw new Error(`${what} failed: ${(result.stderr || result.stdout || '').trim()}`);
};
const xml = value => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
// systemd unit files expand % specifiers and $ variables, and accept C-style quoted words.
const systemdWord = value => `"${String(value).replace(/[\\"]/g, '\\$&').replace(/%/g, '%%').replace(/\$/g, '$$$$')}"`;
const HEADER = 'Generated by dotfiles jobs from jobs/jobs.json; edit that and run `dot jobs sync`.';

// unit: { name, program, runnerLog, schedule }. Each platform maps it to { path: content } files.
const macos = {
  dir: join(homedir(), 'Library/LaunchAgents'),
  prefix: 'me.luanv.jobs.',
  suffix: '.plist',
  files: ({ name, program, runnerLog, schedule }) => ({
    [`${macos.prefix}${name}.plist`]: `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${HEADER} -->
<plist version="1.0">
  <dict>
    <key>Label</key><string>${xml(macos.prefix + name)}</string>
    <key>ProgramArguments</key>
    <array>
      <string>${xml(program)}</string>
      <string>exec</string>
      <string>${xml(name)}</string>
    </array>
    <key>StartCalendarInterval</key>
    <array>
${launchdCalendar(schedule).map(entry => `      <dict>\n${Object.entries(entry)
    .map(([key, value]) => `        <key>${key}</key><integer>${value}</integer>\n`).join('')}      </dict>\n`).join('')}    </array>
    <key>StandardOutPath</key><string>${xml(runnerLog)}</string>
    <key>StandardErrorPath</key><string>${xml(runnerLog)}</string>
    <key>ExitTimeOut</key><integer>30</integer>
  </dict>
</plist>
`,
  }),
  target: name => `gui/${process.getuid()}/${macos.prefix}${name}`,
  loaded: name => run('launchctl', ['print', macos.target(name)]).status === 0,
  // bootout returns before a running job has exited, and bootstrap fails while the old instance is
  // still there. ExitTimeOut gives the runner time to stop the command (SIGTERM, then SIGKILL after
  // 10s) and record the run before launchd kills it; launchd's own default is about 5s.
  bootout(name) {
    run('launchctl', ['bootout', macos.target(name)]);
    for (let waited = 0; macos.loaded(name) && waited < 40_000; waited += 200) {
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 200);
    }
  },
  load(name) {
    macos.bootout(name);
    run('launchctl', ['enable', macos.target(name)]);
    check(run('launchctl', ['bootstrap', `gui/${process.getuid()}`, file(name)]), `launchctl bootstrap ${file(name)}`);
  },
  unload(name) {
    macos.bootout(name);
    rmSync(file(name), { force: true });
  },
  start: name => check(run('launchctl', ['kickstart', macos.target(name)]), `launchctl kickstart ${name}`),
};

const linux = {
  dir: join(process.env.XDG_CONFIG_HOME || join(homedir(), '.config'), 'systemd/user'),
  prefix: 'jobs-',
  suffix: '.timer',
  files: ({ name, program, schedule }) => ({
    [`jobs-${name}.service`]: `# ${HEADER}
[Unit]
Description=dotfiles job ${name}

[Service]
Type=oneshot
ExecStart=${systemdWord(program)} exec ${name}
`,
    [`jobs-${name}.timer`]: `# ${HEADER}
[Unit]
Description=Schedule for dotfiles job ${name}

[Timer]
OnCalendar=${systemdCalendar(schedule)}
Persistent=true

[Install]
WantedBy=timers.target
`,
  }),
  loaded: name => run('systemctl', ['--user', 'is-active', '--quiet', `jobs-${name}.timer`]).status === 0,
  load(name) {
    check(run('systemctl', ['--user', 'daemon-reload']), 'systemctl --user daemon-reload');
    check(run('systemctl', ['--user', 'enable', `jobs-${name}.timer`]), `enabling ${name}`);
    check(run('systemctl', ['--user', 'restart', `jobs-${name}.timer`]), `starting ${name}`);
  },
  unload(name) {
    run('systemctl', ['--user', 'disable', '--now', `jobs-${name}.timer`]);
    for (const unit of [`jobs-${name}.service`, `jobs-${name}.timer`]) rmSync(join(linux.dir, unit), { force: true });
    run('systemctl', ['--user', 'daemon-reload']);
  },
  start: name => check(run('systemctl', ['--user', 'start', '--no-block', `jobs-${name}.service`]),
    `systemctl --user start ${name}`),
};

const platform = process.platform === 'darwin' ? macos : linux;

// The file whose presence means "enabled here".
export const unitFile = name => join(platform.dir, `${platform.prefix}${name}${platform.suffix}`);
const file = unitFile;

export const installedJobs = () => (existsSync(platform.dir) ? readdirSync(platform.dir) : [])
  .filter(name => name.startsWith(platform.prefix) && name.endsWith(platform.suffix))
  .map(name => name.slice(platform.prefix.length, -platform.suffix.length));

// When the unit was last written, or undefined when the job isn't enabled here.
export const installedAt = name => (existsSync(file(name)) ? statSync(file(name)).mtime : undefined);
export const isLoaded = name => platform.loaded(name);
export const startUnit = name => platform.start(name);

// Whether the unit files on disk are what jobs.json would generate now.
export const isCurrent = unit => Object.entries(platform.files(unit))
  .every(([name, content]) => existsSync(join(platform.dir, name)) && readFileSync(join(platform.dir, name), 'utf8') === content);

// Writes and (re)loads the unit when it changed or isn't loaded. Returns whether it did anything.
export function installUnit(unit) {
  if (isCurrent(unit) && platform.loaded(unit.name)) return false;
  mkdirSync(platform.dir, { recursive: true });
  for (const [name, content] of Object.entries(platform.files(unit))) writeFileSync(join(platform.dir, name), content);
  platform.load(unit.name);
  return true;
}

export const uninstallUnit = name => platform.unload(name);
